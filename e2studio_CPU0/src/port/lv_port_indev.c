/**
 * Initialize the touch panel input device
 *
 * Reference: reference_projects/lv_port_renesas_ek_ra8p1/src/port/lv_port_indev.c:95-149
 */
void lv_port_indev_init(void)
{
    fsp_err_t err;

    /*
     * Step 0 (R-006): Create the uT-Kernel synchronization objects
     * (I2C completion event flag / touch IRQ semaphore) BEFORE any FSP
     * open call registers the ISR callbacks that signal them.
     */
    if (!touch_sync_init())
    {
        s_touch_status = TOUCH_STATUS_ERROR;
        return;
    }

    /*
     * Step 1: Create and register LVGL input device
     *
     * Create a pointer-type input device and register the touchpad_read
     * callback. LVGL will call this callback periodically to check for
     * new touch events.
     *
     * Reference: reference_projects/lv_port_renesas_ek_ra8p1/src/port/lv_port_indev.c:104-106
     */
    s_indev_touchpad = lv_indev_create();
    lv_indev_set_type(s_indev_touchpad, LV_INDEV_TYPE_POINTER);
    lv_indev_set_read_cb(s_indev_touchpad, touchpad_read);

#if (1 == INDEV_EVENT_DRIVEN)
    /* Update the input device's running mode to LV_INDEV_MODE_EVENT */
    lv_indev_set_mode(s_indev_touchpad, LV_INDEV_MODE_EVENT);
#endif

    /*
     * Step 2 / 2b / 3: Acquire the IIC1 shared bus.
     *
     * Issue #46: the three steps that used to live here (wait for the camera
     * to release IIC1 -> open g_i2c_master0 -> NULL the rm_comms_i2c
     * semaphore/mutex pointers to select callback mode) moved verbatim into
     * i2c_bus0_open_once() (src/port/i2c_bus0.c), because the touch panel is
     * no longer the only user of this bus: the DA7212 audio CODEC
     * (g_comms_i2c_codec, slave 0x1A) sits on the same shared bus
     * (ra_gen/hal_data.c:14). The order and the semantics are unchanged:
     *
     *   - camera_thread_i2c_done() is still waited on BEFORE the open, which
     *     is what prevents the Issue #93 IIC1 IRQ-context conflict
     *     (r_iic_master.c:784-787).
     *   - the `#if BSP_CFG_RTOS` guarded NULL assignments are still performed
     *     BEFORE RM_COMMS_I2C_Open() below.
     *   - the open happens exactly once even if the audio task gets there
     *     first.
     *
     * What is NEW is that every touch transfer must now be wrapped in
     * i2c_bus0_lock()/i2c_bus0_unlock() (see touchpad_get_xy), because
     * rm_comms_i2c rewrites the shared slave address and lower level callback
     * on every device switch (rm_comms_i2c_driver_ra.c:345-380) and the
     * middleware's own bus mutex does not exist in this build
     * (rm_comms_i2c.h:90-93 with BSP_CFG_RTOS == 0).
     */
    /*
     * Not an assert: assert() reaches newlib's abort() in this build (NDEBUG
     * is not defined) and would hang lvgl_task forever, taking the whole UI
     * with it, while the shell keeps answering. Losing the touch panel is bad;
     * losing the display too is worse. Leave s_touch_status at
     * NOT_INITIALIZED so `touch status` reports it and the LVGL side still
     * comes up.
     */
    /*
     * One call, one lock: the shared master and this device are opened
     * together. Splitting them would let a camera diagnostic close the master
     * in between and make RM_COMMS_I2C_Open() fail with
     * FSP_ERR_COMMS_BUS_NOT_OPEN (see i2c_bus0_open_device).
     *
     * Not an assert: assert() reaches newlib's abort() in this build (NDEBUG
     * is not defined) and would hang lvgl_task forever, taking the whole UI
     * with it, while the shell keeps answering. Losing the touch panel is bad;
     * losing the display too is worse. Leave s_touch_status at
     * NOT_INITIALIZED so `touch status` reports it and LVGL still comes up.
     */
    err = i2c_bus0_open_device(&g_comms_i2c_device0_ctrl, &g_comms_i2c_device0_cfg);
    if (FSP_SUCCESS != err)
    {
        char err_buf[TOUCH_PRINT_BUF_SIZE];
        snprintf(err_buf, sizeof(err_buf),
                 "lv_port_indev: IIC1 shared bus/device open failed (err=0x%lX); touch disabled.\r\n",
                 (unsigned long)err);
        print_to_console(err_buf);
        return;
    }

    /*
     * Step 4: the I2C communication device is already open.
     *
     * RM_COMMS_I2C_Open() - which configures the slave address (0x38 for
     * GT911/FT5X06) and the communication parameters - was performed by
     * i2c_bus0_open_device() above, under the same lock as the master open.
     *
     * Note: The LCD reset (performed in glcdc_port_init) is shared with
     * the touch controller. The touch controller must be initialized
     * after the LCD reset sequence.
     *
     * Reference: reference_projects/lv_port_renesas_ek_ra8p1/src/port/lv_port_indev.c:141-142
     */

    /*
     * Step 5: Open and enable external IRQ for touch events
     *
     * The GT911 INT pin generates a falling-edge interrupt when new
     * touch data is available. The IRQ callback (touch_irq_callback)
     * signals s_touch_irq_semid (tk_sig_sem) to notify the LVGL task.
     *
     * Reference: reference_projects/lv_port_renesas_ek_ra8p1/src/port/lv_port_indev.c:144-148
     */
    /* Same reasoning as the bus open above: an assert() here would abort()
     * and hang lvgl_task, killing the display along with the touch panel. */
    err = R_ICU_ExternalIrqOpen(&g_external_irq0_ctrl, &g_external_irq0_cfg);
    if (FSP_SUCCESS == err)
    {
        err = R_ICU_ExternalIrqEnable(&g_external_irq0_ctrl);
    }

    if (FSP_SUCCESS != err)
    {
        char err_buf[TOUCH_PRINT_BUF_SIZE];
        snprintf(err_buf, sizeof(err_buf),
                 "lv_port_indev: touch IRQ setup failed (err=0x%lX); touch disabled.\r\n",
                 (unsigned long)err);
        print_to_console(err_buf);
        return;
    }

    s_touch_status = TOUCH_STATUS_INITIALIZED;
}

