/**
 * Initialize the touch panel input device
 *
 * Reference: reference_projects/lv_port_renesas_ek_ra8p1/src/port/lv_port_indev.c:95-149
 */
void lv_port_indev_init(void)
{
    fsp_err_t err;

    /*
     * Step 1: Create and register LVGL input device
     *
     * Create a pointer-type input device and register the touchpad_read
     * callback. LVGL will call this callback periodically to check for
     * new touch events.
     *
     * Reference: reference_projects/lv_port_renesas_ek_ra8p1/src/port/lv_port_indev.c:104-106
     */
    s_indev_touchpad = lv_indev_create();
    lv_indev_set_type(s_indev_touchpad, LV_INDEV_TYPE_POINTER);
    lv_indev_set_read_cb(s_indev_touchpad, touchpad_read);

#if (1 == INDEV_EVENT_DRIVEN)
    /* Update the input device's running mode to LV_INDEV_MODE_EVENT */
    lv_indev_set_mode(s_indev_touchpad, LV_INDEV_MODE_EVENT);
#endif

    /*
     * Step 2: Open the I2C bus driver
     *
     * Access the underlying I2C master driver through the RM_COMMS_I2C
     * configuration's extended configuration. The I2C master must be
     * opened before the communication device can be used.
     *
     * Reference: reference_projects/lv_port_renesas_ek_ra8p1/src/port/lv_port_indev.c:115-119
     */
    rm_comms_i2c_bus_extended_cfg_t *p_extend =
        (rm_comms_i2c_bus_extended_cfg_t *)g_comms_i2c_device0_cfg.p_extend;
    i2c_master_instance_t *p_driver_instance =
        (i2c_master_instance_t *)p_extend->p_driver_instance;

    err = p_driver_instance->p_api->open(p_driver_instance->p_ctrl,
                                          p_driver_instance->p_cfg);
    assert(FSP_SUCCESS == err);

    /*
     * Step 3: Create FreeRTOS synchronization objects for I2C bus
     *
     * The RM_COMMS_I2C bus requires:
     *   - A counting semaphore (initial count 0) for blocking on bus operations
     *   - A recursive mutex for bus lock (allows nested I2C transactions)
     *
     * These are created here rather than in the FSP-generated code because
     * the FreeRTOS static allocation functions need to be called at runtime.
     *
     * Reference: reference_projects/lv_port_renesas_ek_ra8p1/src/port/lv_port_indev.c:121-138
     */
#if (2 == BSP_CFG_RTOS)
    /* Create a semaphore for blocking if a semaphore is not NULL */
    if (NULL != p_extend->p_blocking_semaphore)
    {
        *(p_extend->p_blocking_semaphore->p_semaphore_handle) =
            xSemaphoreCreateCountingStatic((UBaseType_t)1,
                                           (UBaseType_t)0,
                                           p_extend->p_blocking_semaphore->p_semaphore_memory);
    }
    /* Create a recursive mutex for bus lock if a recursive mutex is not NULL */
    if (NULL != p_extend->p_bus_recursive_mutex)
    {
        *(p_extend->p_bus_recursive_mutex->p_mutex_handle) =
            xSemaphoreCreateRecursiveMutexStatic(p_extend->p_bus_recursive_mutex->p_mutex_memory);
    }
#endif

    /*
     * Step 4: Open the I2C communication device
     *
     * RM_COMMS_I2C_Open() configures the I2C device with the slave address
     * (0x38 for GT911/FT5X06) and communication parameters.
     *
     * Note: The LCD reset (performed in glcdc_port_init) is shared with
     * the touch controller. The touch controller must be initialized
     * after the LCD reset sequence.
     *
     * Reference: reference_projects/lv_port_renesas_ek_ra8p1/src/port/lv_port_indev.c:141-142
     */
    err = RM_COMMS_I2C_Open(&g_comms_i2c_device0_ctrl, &g_comms_i2c_device0_cfg);
    assert(FSP_SUCCESS == err);

    /*
     * Step 5: Open and enable external IRQ for touch events
     *
     * The GT911 INT pin generates a falling-edge interrupt when new
     * touch data is available. The IRQ callback (touch_irq_callback)
     * gives the g_irq_binary_semaphore to notify the LVGL thread.
     *
     * Reference: reference_projects/lv_port_renesas_ek_ra8p1/src/port/lv_port_indev.c:144-148
     */
    err = R_ICU_ExternalIrqOpen(&g_external_irq0_ctrl, &g_external_irq0_cfg);
    assert(FSP_SUCCESS == err);

    err = R_ICU_ExternalIrqEnable(&g_external_irq0_ctrl);
    assert(FSP_SUCCESS == err);

    s_touch_status = TOUCH_STATUS_INITIALIZED;
}

