/**
 * Wait for I2C transfer completion
 *
 * @details Blocks on the uT-Kernel event flag until either the transfer
 *          completes successfully, aborts with error, or times out.
 *
 * R-006: xEventGroupWaitBits -> tk_wai_flg(TWF_ORW | TWF_BITCLR, ms timeout)
 *        (same pattern as ov5640_i2c_wait_complete in ov5640.c, R-005).
 *        TWF_ORW  = wait for ANY of the bits ("either bit will do")
 *        TWF_BITCLR = clear the satisfied bits on return
 *
 * Reference: reference_projects/lv_port_renesas_ek_ra8p1/src/port/lv_port_indev.c:199-225
 *
 * @retval FSP_SUCCESS       Transfer completed successfully
 * @retval FSP_ERR_ABORTED   Transfer aborted due to I2C error
 * @retval FSP_ERR_TIMEOUT   Transfer timed out (or flag wait failed)
 */
static fsp_err_t i2c_wait(void)
{
    fsp_err_t ret = FSP_SUCCESS;
    UINT flgptn = 0;

    ER ercd = tk_wai_flg(s_touch_i2c_flgid,
                         (UINT)(I2C_TRANSFER_COMPLETE | I2C_TRANSFER_ABORT),
                         TWF_ORW | TWF_BITCLR,
                         &flgptn,
                         (TMO)I2C_TIMEOUT_MS);

    if (E_OK != ercd)
    {
        /* E_TMOUT or other flag error: report as timeout.
         *
         * Issue #46: abort the transfer before the caller releases the bus
         * lock and clear the event flag - a timeout does not stop the lower
         * level transfer, and a late callback would otherwise satisfy the next
         * wait as a false completion (see i2c_bus0_abort_transfer). */
        (void)i2c_bus0_abort_transfer();
        (void)tk_clr_flg(s_touch_i2c_flgid, 0);

        ret = FSP_ERR_TIMEOUT;
    }
    else if ((I2C_TRANSFER_COMPLETE & flgptn) == I2C_TRANSFER_COMPLETE)
    {
        ret = FSP_SUCCESS;
    }
    else
    {
        /* I2C_TRANSFER_ABORT was set */
        ret = FSP_ERR_ABORTED;
    }

    return ret;
}

/**
 * Check if a touch event is pending
 *
 * @details Attempts to take the IRQ semaphore without waiting (TMO_POL).
 *          Returns true if the semaphore was available, indicating that
 *          touch_irq_callback() was called since the last check.
 *
 * R-006: xSemaphoreTake(g_irq_binary_semaphore, 0)
 *        -> tk_wai_sem(s_touch_irq_semid, 1, TMO_POL).
 *
 * Reference: reference_projects/lv_port_renesas_ek_ra8p1/src/port/lv_port_indev.c:227-239
 *
 * @retval true   Touch event is pending (semaphore was taken)
 * @retval false  No touch event pending
 */
static bool touchpad_is_pressed(void)
{
    return (E_OK == tk_wai_sem(s_touch_irq_semid, 1, TMO_POL));
}

/**
 * LVGL touchpad read callback
 *
 * @details Called by LVGL periodically to poll for touch input.
 *
 * In polling mode (INDEV_EVENT_DRIVEN == 0):
 *   - First checks if a touch event is pending via touchpad_is_pressed()
 *   - If pending, reads touch data via I2C
 *   - If not pending, returns the last known state and coordinates
 *   - This minimizes I2C bus traffic by only reading when touch IRQ fires
 *
 * In event-driven mode (INDEV_EVENT_DRIVEN == 1):
 *   - Reads touch data directly on every LVGL poll
 *
 * Reference: reference_projects/lv_port_renesas_ek_ra8p1/src/port/lv_port_indev.c:246-273
 *
 * @param indev  LVGL input device handle (unused)
 * @param data   Output: touch state and coordinates
 */
static void touchpad_read(lv_indev_t *indev, lv_indev_data_t *data)
{
    FSP_PARAMETER_NOT_USED(indev);

    data->state = LV_INDEV_STATE_RELEASED;

#if (1 == INDEV_EVENT_DRIVEN)
    touchpad_get_xy(data);
#else
    /*
     * Polling mode: Save the pressed coordinates and the state.
     * Only perform I2C read when the IRQ semaphore indicates new data.
     *
     * Reference: reference_projects/lv_port_renesas_ek_ra8p1/src/port/lv_port_indev.c:256-271
     */
    static lv_indev_state_t last_state = LV_INDEV_STATE_RELEASED;
    static lv_point_t last_point = {.x = 0, .y = 0};

    if (touchpad_is_pressed()) {
        touchpad_get_xy(data);
        last_state = data->state;
        last_point.x = data->point.x;
        last_point.y = data->point.y;
    }
    else
    {
        data->state   = last_state;
        data->point.x = last_point.x;
        data->point.y = last_point.y;
    }
#endif
}

/**
 * Read touch coordinates from the FT5X06/GT911 controller
 *
 * @details Performs an I2C write-read transaction to read the touch status
 *          register (0x02) and all five touch point data sets. Parses the
 *          raw bit-field data into x/y coordinates and event types.
 *
 *          I2C transaction:
 *            Write: 1 byte (register address 0x02)
 *            Read:  31 bytes (1 byte status + 5 x 6 bytes touch data)
 *
 *          Only the first touch point is reported to LVGL (single-touch).
 *          Multi-touch data is parsed but not used by LVGL's pointer model.
 *
 * Reference: reference_projects/lv_port_renesas_ek_ra8p1/src/port/lv_port_indev.c:275-338
 *
 * @param data  Output: touch state and coordinates for LVGL
 */
static void touchpad_get_xy(lv_indev_data_t *data)
{
    fsp_err_t err;
    rm_comms_write_read_params_t write_read_params;
    ft5x06_payload_t touch_payload;
    uint8_t event;
    uint8_t reg;
    uint8_t touch_count;

    reg = FT5X06_REG_TD_STATUS;

    write_read_params.src_bytes  = 1;
    write_read_params.p_src      = &reg;
    write_read_params.p_dest     = (uint8_t *)&touch_payload;
    write_read_params.dest_bytes = sizeof(ft5x06_payload_t);

    /*
     * Write TD_STATUS address, then read status + all five touch point registers.
     *
     * Issue #46: the submit AND the completion wait are inside the IIC1 bus
     * lock. Both are required to be atomic with respect to the other bus user
     * (DA7212): rm_comms_i2c_bus_reconfigure() rewrites the shared
     * p_current_ctrl / slave address / lower level callback whenever the
     * requesting device differs from the previous one
     * (ra/fsp/src/rm_comms_i2c/rm_comms_i2c_driver_ra.c:345-380), so a
     * concurrent codec transfer between the submit and the completion would
     * redirect this transfer's callback.
     *
     * Reference: reference_projects/lv_port_renesas_ek_ra8p1/src/port/lv_port_indev.c:293-294
     */
    err = i2c_bus0_lock();
    if (FSP_SUCCESS != err)
    {
        /* Bus busy/unavailable (>= I2C_BUS0_LOCK_TIMEOUT_MS): report
         * "released" for this cycle rather than corrupting a transfer that
         * belongs to another device on the bus.
         *
         * Issue #46: this is the ONLY path out of touchpad_get_xy() that
         * reports RELEASED without having talked to the controller, and it
         * leaves s_touch_read_count untouched. Counting it separately is what
         * distinguishes "the bus lock failed" from "the panel reported no
         * touch" in touch status - the two look identical from the outside. */
        s_touch_lock_fail_count++;
        s_touch_last_lock_err = err;
        data->state = LV_INDEV_STATE_RELEASED;
        return;
    }

    /*
     * Issue #46: these two failures used to be assert(). NDEBUG is not defined
     * in this build, so assert() reaches newlib's abort() and hangs WHATEVER
     * TASK is running - here that is lvgl_task, i.e. one transient I2C hiccup
     * freezes the whole UI while the shell keeps answering, which is a very
     * confusing failure mode to debug.
     *
     * That risk is higher now than before this Issue: the DA7212 is a second
     * user of this bus, so a touch transfer can now fail for reasons outside
     * the touch driver. A dropped sample is not worth killing the UI for -
     * count it, report "released" for this cycle and let the next poll retry.
     */
    err = RM_COMMS_I2C_WriteRead(&g_comms_i2c_device0_ctrl, write_read_params);
    if (FSP_SUCCESS != err)
    {
        (void)i2c_bus0_unlock();
        s_touch_xfer_fail_count++;
        s_touch_last_xfer_err = err;
        data->state = LV_INDEV_STATE_RELEASED;
        return;
    }

    err = i2c_wait();

    (void)i2c_bus0_unlock();

    if (FSP_SUCCESS != err)
    {
        s_touch_xfer_fail_count++;
        s_touch_last_xfer_err = err;
        data->state = LV_INDEV_STATE_RELEASED;
        return;
    }

    /* Snapshot the raw bytes before any parsing (see s_touch_raw). */
    memcpy(s_touch_raw, &touch_payload, sizeof(s_touch_raw));
    s_touch_raw_valid = true;

    /* Extract active touch count from lower nibble */
    touch_count = touch_payload.num_points_active & 0x0F;

    if (FT5X06_NUM_POINTS < touch_count)
    {
        /* Garbage count (bus glitch, or the answer came from another slave).
         *
         * Drop the whole sample - do NOT clamp and parse. If the count is
         * corrupt the point records behind it are corrupt too, so parsing them
         * would hand LVGL a PRESSED event at an arbitrary coordinate and turn
         * a detected corruption into a phantom tap. The next poll retries. */
        s_touch_xfer_fail_count++;
        data->state = LV_INDEV_STATE_RELEASED;
        return;
    }

    /* Reset all points to released before parsing new data */
    for (uint8_t i = 0; i < FT5X06_NUM_POINTS; i++)
    {
        s_touch_data.point[i].event = LV_INDEV_STATE_RELEASED;
    }

    /*
     * Process the raw data for the touch point(s) into useful coordinates.
     *
     * Reference: reference_projects/lv_port_renesas_ek_ra8p1/src/port/lv_port_indev.c:310-329
     */
    for (uint8_t i = 0; i < touch_count; i++)
    {
        s_touch_data.point[i].x = (uint16_t)extract_x(touch_payload.data_raw[i]);
        s_touch_data.point[i].y = (uint16_t)extract_y(touch_payload.data_raw[i]);
        event                   = extract_e(touch_payload.data_raw[i]);

        /* Set event type based on received data */
        switch (event)
        {
            case FT5X06_DOWN:
            case FT5X06_CONTACT:
                s_touch_data.point[i].event = LV_INDEV_STATE_PRESSED;
                break;
            case FT5X06_UP:
            case FT5X06_NO_EVENT:
            default:
                s_touch_data.point[i].event = LV_INDEV_STATE_RELEASED;
                break;
        }
    }

    /*
     * Report the first touch point to LVGL.
     * Only report coordinates when the point is pressed.
     *
     * Reference: reference_projects/lv_port_renesas_ek_ra8p1/src/port/lv_port_indev.c:331-337
     */
    data->state = s_touch_data.point[0].event;
    if (LV_INDEV_STATE_PRESSED == s_touch_data.point[0].event)
    {
        data->point.x = s_touch_data.point[0].x;
        data->point.y = s_touch_data.point[0].y;
    }

    /* Update diagnostic counters */
    s_touch_read_count++;
    s_last_touch_state = data->state;
    if (LV_INDEV_STATE_PRESSED == data->state)
    {
        s_last_touch_x = (int16_t)data->point.x;
        s_last_touch_y = (int16_t)data->point.y;
    }
}

