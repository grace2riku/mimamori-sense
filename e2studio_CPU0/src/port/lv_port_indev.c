/**
 * "touch status" sub-command handler
 *
 * @details Displays touch panel initialization state, operating mode,
 *          and diagnostic counters.
 */
static void touch_cmd_status(void)
{
    char buf[TOUCH_PRINT_BUF_SIZE];
    const char *status_str;

    switch (s_touch_status) {
        case TOUCH_STATUS_INITIALIZED:
            status_str = "Initialized";
            break;
        case TOUCH_STATUS_ERROR:
            status_str = "ERROR";
            break;
        default:
            status_str = "Not initialized";
            break;
    }

    print_to_console("[Touch Panel Status]\r\n");

    snprintf(buf, sizeof(buf), "  Status       : %s\r\n", status_str);
    print_to_console(buf);

    snprintf(buf, sizeof(buf), "  Mode         : %s\r\n",
             INDEV_EVENT_DRIVEN ? "Event-driven" : "Polling (IRQ-triggered)");
    print_to_console(buf);

    snprintf(buf, sizeof(buf), "  LVGL indev   : %s\r\n",
             (s_indev_touchpad != NULL) ? "Registered" : "Not registered");
    print_to_console(buf);

    snprintf(buf, sizeof(buf), "  Read count   : %lu\r\n",
             (unsigned long)s_touch_read_count);
    print_to_console(buf);

    snprintf(buf, sizeof(buf), "  Last state   : %s\r\n",
             (s_last_touch_state == LV_INDEV_STATE_PRESSED) ? "PRESSED" : "RELEASED");
    print_to_console(buf);

    if (s_last_touch_x >= 0 && s_last_touch_y >= 0) {
        snprintf(buf, sizeof(buf), "  Last coord   : (%d, %d)\r\n",
                 s_last_touch_x, s_last_touch_y);
        print_to_console(buf);
    } else {
        print_to_console("  Last coord   : (no touch recorded)\r\n");
    }
}

/**
 * "touch info" sub-command handler
 *
 * @details Displays touch controller hardware information.
 */
static void touch_cmd_info(void)
{
    char buf[TOUCH_PRINT_BUF_SIZE];

    print_to_console("[Touch Controller Information]\r\n");
    print_to_console("  Controller   : GT911 (FT5X06-compatible)\r\n");
    print_to_console("  Interface    : I2C\r\n");

    snprintf(buf, sizeof(buf), "  I2C Address  : 0x38\r\n");
    print_to_console(buf);

    snprintf(buf, sizeof(buf), "  IRQ Channel  : %d (falling edge)\r\n", TOUCH_IRQ_CHANNEL);
    print_to_console(buf);

    snprintf(buf, sizeof(buf), "  Max Points   : %d\r\n", FT5X06_NUM_POINTS);
    print_to_console(buf);

    print_to_console("  Resolution   : 1024 x 600 (matches LCD)\r\n");

    print_to_console("[Register Map]\r\n");

    snprintf(buf, sizeof(buf), "  TD_STATUS    : 0x%02X (touch count)\r\n",
             FT5X06_REG_TD_STATUS);
    print_to_console(buf);

    snprintf(buf, sizeof(buf), "  Payload size : %u bytes\r\n",
             (unsigned int)sizeof(ft5x06_payload_t));
    print_to_console(buf);
}

/**
 * "touch read" sub-command handler
 *
 * @details Performs a single touch data read and displays the result.
 *          This reads directly from I2C regardless of the IRQ state.
 */
static void touch_cmd_read(void)
{
    char buf[TOUCH_PRINT_BUF_SIZE];

    if (s_touch_status != TOUCH_STATUS_INITIALIZED) {
        print_to_console("  Error: Touch panel is not initialized.\r\n");
        return;
    }

    print_to_console("[Touch Read (single)]\r\n");

    /* Perform a direct read */
    lv_indev_data_t data;
    data.state = LV_INDEV_STATE_RELEASED;
    data.point.x = 0;
    data.point.y = 0;

    touchpad_get_xy(&data);

    snprintf(buf, sizeof(buf), "  State  : %s\r\n",
             (data.state == LV_INDEV_STATE_PRESSED) ? "PRESSED" : "RELEASED");
    print_to_console(buf);

    snprintf(buf, sizeof(buf), "  Coord  : (%ld, %ld)\r\n",
             (long)data.point.x, (long)data.point.y);
    print_to_console(buf);

    /* Show all active points from the last read */
    for (uint8_t i = 0; i < FT5X06_NUM_POINTS; i++) {
        if (s_touch_data.point[i].event == LV_INDEV_STATE_PRESSED) {
            snprintf(buf, sizeof(buf), "  Point[%d]: (%u, %u) PRESSED\r\n",
                     i, s_touch_data.point[i].x, s_touch_data.point[i].y);
            print_to_console(buf);
        }
    }
}

/**
 * "touch mon" sub-command handler
 *
 * @details Monitors touch events for a specified duration (default: 5 seconds).
 *          Displays coordinates and state changes in real-time.
 *
 * @param argc  Argument count
 * @param argv  Argument vector (argv[2] = duration in seconds)
 */
static void touch_cmd_mon(int argc, char **argv)
{
    char buf[TOUCH_PRINT_BUF_SIZE];
    uint32_t duration_sec = 5;

    if (s_touch_status != TOUCH_STATUS_INITIALIZED) {
        print_to_console("  Error: Touch panel is not initialized.\r\n");
        return;
    }

    /* Parse optional duration argument */
    if (argc >= 3) {
        cmd_parse_result_t result = cmd_parse_uint32(argv[2]);
        if (result.valid && result.value > 0 && result.value <= 60) {
            duration_sec = result.value;
        } else {
            print_to_console("  Duration must be 1-60 seconds.\r\n");
            return;
        }
    }

    snprintf(buf, sizeof(buf), "[Touch Monitor - %lu seconds (press Ctrl+C to stop)]\r\n",
             (unsigned long)duration_sec);
    print_to_console(buf);

    uint32_t start_count = s_touch_read_count;
    lv_indev_state_t prev_state = LV_INDEV_STATE_RELEASED;

    for (uint32_t elapsed = 0; elapsed < duration_sec * 10; elapsed++) {
        /* Check current state (updated by LVGL thread) */
        lv_indev_state_t current_state = s_last_touch_state;
        int16_t x = s_last_touch_x;
        int16_t y = s_last_touch_y;

        /* Report state changes */
        if (current_state != prev_state) {
            if (current_state == LV_INDEV_STATE_PRESSED) {
                snprintf(buf, sizeof(buf), "  [%lu.%lus] PRESSED  (%d, %d)\r\n",
                         (unsigned long)(elapsed / 10),
                         (unsigned long)(elapsed % 10),
                         x, y);
                print_to_console(buf);
            } else {
                snprintf(buf, sizeof(buf), "  [%lu.%lus] RELEASED\r\n",
                         (unsigned long)(elapsed / 10),
                         (unsigned long)(elapsed % 10));
                print_to_console(buf);
            }
            prev_state = current_state;
        }
        else if (current_state == LV_INDEV_STATE_PRESSED) {
            /* Periodic position update while pressed (every 500ms) */
            if ((elapsed % 5) == 0) {
                snprintf(buf, sizeof(buf), "  [%lu.%lus] CONTACT  (%d, %d)\r\n",
                         (unsigned long)(elapsed / 10),
                         (unsigned long)(elapsed % 10),
                         x, y);
                print_to_console(buf);
            }
        }

        vTaskDelay(pdMS_TO_TICKS(100));
    }

    uint32_t total_reads = s_touch_read_count - start_count;
    snprintf(buf, sizeof(buf), "  Monitor complete. %lu touch reads during %lu seconds.\r\n",
             (unsigned long)total_reads, (unsigned long)duration_sec);
    print_to_console(buf);
}

/**
 * NT-Shell "touch" command handler
 *
 * @details Provides touch panel diagnostic sub-commands.
 *
 * Reference: lv_port_indev.h (usrcmd_touch declaration)
 */
int usrcmd_touch(int argc, char **argv)
{
    if (argc < 2) {
        cmd_print_usage("touch", "<subcommand>");
        print_to_console("  status - Show touch panel initialization state\r\n");
        print_to_console("  info   - Show touch controller information\r\n");
        print_to_console("  read   - Read current touch data once\r\n");
        print_to_console("  mon    - Monitor touch events: mon [seconds]\r\n");
        return CMD_ERR_USAGE;
    }

    if (ntlibc_strcmp(argv[1], "status") == 0) {
        touch_cmd_status();
        return CMD_OK;
    }

    if (ntlibc_strcmp(argv[1], "info") == 0) {
        touch_cmd_info();
        return CMD_OK;
    }

    if (ntlibc_strcmp(argv[1], "read") == 0) {
        touch_cmd_read();
        return CMD_OK;
    }

    if (ntlibc_strcmp(argv[1], "mon") == 0) {
        touch_cmd_mon(argc, argv);
        return CMD_OK;
    }

    /* Unknown sub-command */
    {
        char buf[TOUCH_PRINT_BUF_SIZE];
        snprintf(buf, sizeof(buf), "Error: Unknown sub-command '%s'.\r\n", argv[1]);
        print_to_console(buf);
    }

    cmd_print_usage("touch", "<subcommand>");
    print_to_console("  status - Show touch panel initialization state\r\n");
    print_to_console("  info   - Show touch controller information\r\n");
    print_to_console("  read   - Read current touch data once\r\n");
    print_to_console("  mon    - Monitor touch events: mon [seconds]\r\n");

    return CMD_ERR_INVALID_ARG;
}
